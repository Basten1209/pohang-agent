/** `{name}` placeholders are filled from `vars`. */
export const translate = (
  locale: Locale,
  key: MessageKey,
  vars: Record<string, string | number> = {},
) =>
  (dictionaries[locale][key] ?? all[key]).replace(/\{(\w+)\}/g, (_, k) =>
    String(vars[k] ?? `{${k}}`),
  )

