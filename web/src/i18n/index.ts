/** 90 → "1시간 30분" / "1 h 30 min" / "1時間30分" / "1小时30分钟". */
export const durationText = (locale: Locale, min: number) => {
  const h = Math.floor(min / 60)
  const m = min % 60
  const unit = {
    ko: { h: '시간', m: '분', sep: ' ' },
    en: { h: ' h', m: ' min', sep: ' ' },
    ja: { h: '時間', m: '分', sep: '' },
    zh: { h: '小时', m: '分钟', sep: '' },
  }[locale]
  if (!h) return `${m}${unit.m}`
  return m ? `${h}${unit.h}${unit.sep}${m}${unit.m}` : `${h}${unit.h}`
}
