// Fill place thumbnails from Korea Tourism (TourAPI KorService2).
//
//   node --env-file=.env scripts/seed-images.mjs
//
// Needs DATA_GO_KR_SERVICE_KEY. For each place below it searches TourAPI by
// keyword inside Pohang, takes the first result's representative image, and
// writes src/core/seed/images.ts with the URL and its source (contentId,
// 공공누리 type) so the credit travels with the photo. Places without a
// specific venue (generic cafes, food streets) keep their icon.

import { writeFileSync } from 'node:fs'

const queries = {
  event: '영일대해수욕장',
  food: '구룡포시장',
  street: '구룡포 일본인 가옥거리',
  'gp-museum': '구룡포과메기문화관',
  'hm-hand': '호미곶해맞이광장',
  'hm-museum': '국립등대박물관',
  'yd-pavilion': '영일대 해상누각',
  'yd-spacewalk': '스페이스워크',
  'yd-art': '포항시립미술관',
  'jd-market': '죽도시장',
  'jd-canalhall': '포항운하관',
  'jd-cruise': '포항크루즈',
  'jd-canal': '포항운하',
}

const raw = process.env.DATA_GO_KR_SERVICE_KEY?.trim()
if (!raw) {
  console.error('DATA_GO_KR_SERVICE_KEY is not set.')
  process.exit(1)
}
const key = /%[0-9A-Fa-f]{2}/.test(raw) ? decodeURIComponent(raw) : raw

const search = async (keyword) => {
  const url = new URL('https://apis.data.go.kr/B551011/KorService2/searchKeyword2')
  const params = {
    serviceKey: key,
    MobileOS: 'ETC',
    MobileApp: 'RUN2',
    _type: 'json',
    keyword,
    arrange: 'O',
    numOfRows: '20',
    pageNo: '1',
  }
  for (const [k, v] of Object.entries(params)) url.searchParams.set(k, v)
  const res = await fetch(url)
  const text = await res.text()
  if (!res.ok || text.trimStart().startsWith('<'))
    throw new Error(`${keyword}: ${text.slice(0, 160)}`)
  const items = JSON.parse(text)?.response?.body?.items?.item ?? []
  const list = Array.isArray(items) ? items : [items]
  return list.find((i) => String(i.addr1 ?? '').includes('포항') && i.firstimage)
}

const out = {}
for (const [id, keyword] of Object.entries(queries)) {
  try {
    const hit = await search(keyword)
    if (!hit) {
      console.log(`- ${id}: no image for "${keyword}"`)
      continue
    }
    out[id] = {
      url: String(hit.firstimage).replace(/^http:/, 'https:'),
      contentId: String(hit.contentid),
      title: String(hit.title),
      license: String(hit.cpyrhtDivCd ?? ''),
    }
    console.log(`✓ ${id}: ${hit.title}`)
  } catch (e) {
    console.log(`✗ ${id}: ${e.message}`)
  }
}

const body = `// Generated by scripts/seed-images.mjs from Korea Tourism (TourAPI).
// Credit: 한국관광공사. \`license\` is the 공공누리 type (cpyrhtDivCd).
export type PlaceImage = {
  url: string
  contentId: string
  title: string
  license: string
}

export const images: Record<string, PlaceImage> = ${JSON.stringify(out, null, 2)}
`
writeFileSync(new URL('../src/core/seed/images.ts', import.meta.url), body)
console.log(`wrote ${Object.keys(out).length} images`)
